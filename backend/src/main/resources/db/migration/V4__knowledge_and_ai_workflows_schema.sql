CREATE TABLE IF NOT EXISTS knowledge_articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_key VARCHAR(32) NOT NULL UNIQUE,
    title VARCHAR(300) NOT NULL,
    category VARCHAR(64) NOT NULL,
    tags VARCHAR(512),
    content TEXT NOT NULL,
    embedding_vector TEXT NOT NULL,
    published BOOLEAN NOT NULL DEFAULT TRUE,
    view_count BIGINT NOT NULL DEFAULT 0,
    created_by VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_kb_articles_category ON knowledge_articles (category);

CREATE TABLE IF NOT EXISTS ai_approval_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
    ticket_key VARCHAR(32) NOT NULL,
    tool_name VARCHAR(100) NOT NULL,
    action_summary VARCHAR(500) NOT NULL,
    parameters_json TEXT NOT NULL,
    ai_reasoning TEXT NOT NULL,
    confidence DOUBLE PRECISION NOT NULL DEFAULT 0.90,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    requested_by VARCHAR(255) NOT NULL,
    decided_by VARCHAR(255),
    decision_reason TEXT,
    execution_result TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    decided_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_ai_approvals_status ON ai_approval_requests (status);
CREATE INDEX IF NOT EXISTS idx_ai_approvals_ticket_id ON ai_approval_requests (ticket_id);
