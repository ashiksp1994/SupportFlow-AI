-- Phase 5 Remediation:
--   1. Multi-organisation tenant isolation columns on user_details & knowledge_articles
--   2. Optimistic locking (@Version) on tickets & ai_approval_requests
--   3. Document chunking table (knowledge_chunks) for grounded RAG retrieval
--   4. Composite & foreign-key indexes for tenant-scoped query performance
-- =============================================================================

ALTER TABLE user_details ADD COLUMN IF NOT EXISTS organisation_id BIGINT;

ALTER TABLE knowledge_articles ADD COLUMN IF NOT EXISTS organisation_id BIGINT;

ALTER TABLE tickets ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0;

ALTER TABLE ai_approval_requests ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS knowledge_chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id BIGINT NOT NULL REFERENCES knowledge_articles(id) ON DELETE CASCADE,
    article_key VARCHAR(32) NOT NULL,
    organisation_id BIGINT,
    chunk_index INT NOT NULL,
    chunk_text TEXT NOT NULL,
    embedding_vector TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_user_details_org_id ON user_details (organisation_id);
CREATE INDEX IF NOT EXISTS idx_customers_org_id ON customers (organisation_id);
CREATE INDEX IF NOT EXISTS idx_tickets_org_status_priority ON tickets (organisation_id, status, priority);
CREATE INDEX IF NOT EXISTS idx_tickets_customer_id ON tickets (customer_id);
CREATE INDEX IF NOT EXISTS idx_tickets_assigned_agent ON tickets (assigned_agent_username);
CREATE INDEX IF NOT EXISTS idx_kb_articles_org_category ON knowledge_articles (organisation_id, category);
CREATE INDEX IF NOT EXISTS idx_kb_chunks_article_id ON knowledge_chunks (article_id);
CREATE INDEX IF NOT EXISTS idx_kb_chunks_org_id ON knowledge_chunks (organisation_id);
CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at ON audit_logs (created_at);
